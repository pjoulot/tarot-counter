const DICTS = { fr, en };

export function translator(lang: "fr" | "en") {
  const d = DICTS[lang];
  // `count` picks the singular form when one exists (French treats 0 and 1 as singular).
  return (key: Key, vars?: Record<string, string | number> & { count?: number }): string => {
    const c = vars?.count;
    const one = `${key}_one` as Key;
    const singular = c !== undefined && (lang === "fr" ? Math.abs(c) < 2 : Math.abs(c) === 1);
    let s: string = singular && one in d ? d[one] : d[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
export type T = ReturnType<typeof translator>;

